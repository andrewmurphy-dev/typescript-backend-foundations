//what is a type alias !?

//for example


type level = number;

//here , number is a built-in typescript type 


//type alias , is the "level " in the const 

//it lets you create your own name for your type ! 


//for example 


type score = number;

const playerScore: score = 950;

//so remember 

//type score = number;
//this is not a variable 


